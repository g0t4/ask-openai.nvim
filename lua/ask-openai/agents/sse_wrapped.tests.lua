local SSEWrapped = require("ask-openai.agents.sse_wrapped")

describe("SSEWrapped", function()
    it("reports no choices when choices is nil", function()
        local wrapped = SSEWrapped.new({ model = "m" })
        assert.is_false(wrapped:has_choice())
        assert.is_true(wrapped:no_choices())
        assert.is_nil(wrapped:first_choice())
    end)

    it("reports no choices when choices is empty", function()
        local wrapped = SSEWrapped.new({ choices = {} })
        assert.is_false(wrapped:has_choice())
        assert.is_true(wrapped:no_choices())
        assert.is_nil(wrapped:first_choice())
    end)

    it("returns the first choice and its finish_reason", function()
        local choice = { delta = { content = "x" }, finish_reason = "stop" }
        local wrapped = SSEWrapped.new({ choices = { choice } })
        assert.is_true(wrapped:has_choice())
        assert.is_false(wrapped:no_choices())
        assert.equals(choice, wrapped:first_choice())
        assert.equals("stop", wrapped:finish_reason())
        assert.is_true(wrapped:is_finished())
    end)

    it("treats vim.NIL finish_reason as not finished", function()
        local wrapped = SSEWrapped.new({ choices = { { finish_reason = vim.NIL } } })
        assert.is_nil(wrapped:finish_reason())
        assert.is_false(wrapped:is_finished())
    end)

    it("treats missing choices as not finished", function()
        local wrapped = SSEWrapped.new({})
        assert.is_nil(wrapped:finish_reason())
        assert.is_false(wrapped:is_finished())
    end)

    it("nil_ifies vim.NIL in the ctor", function()
        local raw = { choices = { { delta = { content = vim.NIL }, finish_reason = vim.NIL } } }
        local wrapped = SSEWrapped.new(raw)
        assert.is_nil(wrapped:first_choice().delta.content)
        assert.is_nil(wrapped:finish_reason())
    end)

    it("detects errors", function()
        local wrapped = SSEWrapped.new({ error = { code = 503, message = "Loading model", type = "unavailable_error" } })
        assert.is_true(wrapped:has_error())
        assert.is_false(SSEWrapped.new({}):has_error())
    end)
end)
